TRACKS = ["Revenue", "Deliver", "Build", "Company", "Direction"]

GLOSS = {
    "Revenue": "Demand, then sales, then the relationship after the sale.",
    "Deliver": "Client work: won deal to accepted delivery, then support.",
    "Build": "The software factory: requirements to shipped product, then upkeep.",
    "Company": "Finance, billing and legal, so the entity stays solvent and lawful.",
    "Direction": "Planning, decisions, market view and analysis.",
}


def audit():
    problems = []
    names = [s[2] for s in S]
    if len(names) != len(set(names)):
        problems.append("duplicate skill name")
    seen_triggers = {}
    for track, role, name, trigger, *_ in S:
        key = (track, trigger.lower())
        if key in seen_triggers:
            problems.append(f"{track}: {name} and {seen_triggers[key]} share the trigger {trigger!r}")
        seen_triggers[key] = name
    pairs = {(t, r) for t, role, *_ in S for r in [role]}
    declared = {(t, r) for t, roles in ROLES.items() for r, _, _ in roles}
    for missing in sorted(declared - pairs):
        problems.append(f"role with no skill: {missing}")
    for extra in sorted(pairs - declared):
        problems.append(f"skill on undeclared role: {extra}")
    return problems


def emit():
    total = len(S)
    have = sum(1 for s in S if s[7] == "have")
    partial = sum(1 for s in S if s[7] == "partial")
    written = have + partial
    out = [
        "# The business, as roles and skills",
        "",
        f"{total} skills in {len(TRACKS)} tracks, under {sum(len(v) for v in ROLES.values())} roles. "
        "Three are written in this repository; the rest are named and unbuilt, and the state is marked on every row.",
        "",
        "Delivery is split in two, because client work and building software fail in different ways, get fixed by different people and close differently. "
        "A delivered engagement ends with access removed and a closure record. A product release repeats forever.",
        "",
        "## How to read it",
        "",
        "A role states the objective and the scope, so a reader can place themselves before reading a single skill. "
        "A skill states the event that starts it, the object it owns, what it produces, and how its work is proved.",
        "",
        "| Track | Purpose |",
        "|---|---|",
    ]
    for t in TRACKS:
        out.append(f"| **{t}** | {GLOSS[t]} |")
    out += [
        "",
        "## The routing rule",
        "",
        "No two skills in a track share a trigger event. If two could fire on the same event, the assistant guesses, and the guess is the bug. "
        "That rule is enforced by `tools/skill_map.py`, which fails on a shared trigger, a role with no skill, or a skill on a role that does not exist.",
        "",
        "## Coverage",
        "",
        f"{total} skills: {written} written or partially written, {total - written} named and unbuilt.",
        "",
    ]
    for t in TRACKS:
        rows = [s for s in S if s[0] == t]
        st = {k: sum(1 for r in rows if r[7] == k) for k in ("have", "partial", "new")}
        out.append(f"### {t}")
        out.append("")
        out.append(f"*{GLOSS[t]}*  ")
        out.append(f"{len(rows)} skills across {len(ROLES[t])} roles: {st['have']} written, {st['partial']} partial, {st['new']} not built.")
        out.append("")
        out.append("| Role | Objective | Scope |")
        out.append("|---|---|---|")
        for role, obj, scope in ROLES[t]:
            out.append(f"| **{role}** | {obj} | {scope} |")
        out.append("")
        out.append("| Skill | Role | Starts when | Produces | Proved by | State |")
        out.append("|---|---|---|---|---|---|")
        for track, role, name, trigger, produces, mechanism, proof, state in rows:
            out.append(f"| `{name}` | {role} | {trigger} | {produces} | {proof} | {state} |")
        out.append("")
    out += [
        "## What is a rule, not a skill",
        "",
        "Retention, recovery and scheduling are policies and workflows. Approval, authority, evidence, state, exceptions, obligations and notification "
        "are contracts shared by every skill, written once in `06-conventions.md`. A skill that restates a contract is how two skills start disagreeing.",
        "",
        "## Decisions behind this map",
        "",
        "- Roles come before skills, because a title carries an objective and a scope.",
        "- Merge two candidates when they share a trigger event, an output object and an owner of state. Keep them apart when the output is a different artefact with its own lifecycle.",
        "- The design system is about developing with a system, not curating one: the rules live in the skill, the documents live in templates, and conformance is checked when a change is reviewed.",
        "- Client support and product maintenance stay separate: different owners, different clocks.",
        "",
    ]
    path = os.path.join(ROOT, "docs", "business-system", "02-skill-map.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out))
    return path


if __name__ == "__main__":
    problems = audit()
    if "--emit" in sys.argv:
        print("wrote", emit())
    for p in problems:
        print("PROBLEM:", p)
    print(f"{len(S)} skills, {len(TRACKS)} tracks, {sum(len(v) for v in ROLES.values())} roles")
    sys.exit(1 if problems else 0)
